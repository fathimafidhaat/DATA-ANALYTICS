#CASE WHEN - conditional logic
#Classify products into price bands
SELECT product_name,amount,
      CASE
          WHEN amount>=200000 THEN 'Over Price'
          WHEN amount>=75000  THEN 'High Price'
          WHEN amount>=50000  THEN 'Medium Price'
          WHEN amount>=20000  THEN 'Lower Price'
          ELSE'Very lower'
	  END AS price_band
FROM sales;